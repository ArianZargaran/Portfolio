#!/usr/bin/env node
/**
 * Import Dusk's HOTSPOT_BOXES_*.json into the laptop hit areas.
 *
 *   node scripts/hotspots/import-hotspots.mjs <boxes.json>             validate + diff vs live
 *   node scripts/hotspots/import-hotspots.mjs <boxes.json> --write     also regenerate laptop.generated.ts
 *   ... --preview <out.md>    write a preview diff report (nothing in app/ changes)
 *   ... --against <mod.ts>    diff against another module (HIT_OBJECTS or LAPTOP_* exports)
 *
 * Exit 1 on validation errors (nothing is written). Needs Node >= 22.18
 * (runs the TypeScript modules with Node's type stripping).
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const GENERATED = resolve(root, "app/scene/hotspots/laptop.generated.ts");

const args = process.argv.slice(2);
const input = args.find((a) => !a.startsWith("--") && !isValueOf(a));
function isValueOf(a) {
  const i = args.indexOf(a);
  return i > 0 && ["--preview", "--against"].includes(args[i - 1]);
}
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
if (!input) {
  console.error(
    "usage: import-hotspots.mjs <HOTSPOT_BOXES_*.json> [--write] [--preview out.md] [--against mod.ts]",
  );
  process.exit(2);
}

const { importHotspotBoxes, diffLaptop, toLaptopData } = await import(
  pathToFileURL(resolve(root, "app/scene/hotspots/import.ts")).href
);
const M = await import(
  pathToFileURL(resolve(root, "app/scene/hotspots/mapping.ts")).href
);
const cfg = {
  map: M.HOTSPOT_MAP,
  noHit: M.NO_HIT_BOXES,
  reference: M.REFERENCE_BOXES,
  mustStayClear: M.MUST_STAY_CLEAR,
  stacking: M.STACKING_RULES,
  defaultOrder: M.DEFAULT_HIT_ORDER,
  extraRects: M.LOCAL_EXTRA_RECTS,
};

const raw = readFileSync(resolve(input));
const sha256 = createHash("sha256").update(raw).digest("hex");
const res = importHotspotBoxes(JSON.parse(raw.toString("utf8")), cfg);

async function loadBaseline(path) {
  if (!path || !existsSync(path)) return { order: [], rects: {} };
  const mod = await import(pathToFileURL(path).href);
  if (mod.HIT_OBJECTS)
    return {
      order: mod.HIT_OBJECTS.map((o) => o.id),
      rects: Object.fromEntries(
        mod.HIT_OBJECTS.map((o) => [o.id, o.rects.laptop]),
      ),
    };
  return { order: mod.LAPTOP_HIT_ORDER, rects: mod.LAPTOP_RECTS };
}
const againstPath = opt("--against") ? resolve(opt("--against")) : GENERATED;
const before = await loadBaseline(againstPath);
const diff = diffLaptop(before, toLaptopData(res));

console.log(
  `${basename(input)}  v${res.version}  sha256 ${sha256.slice(0, 12)}  ${res.ok ? "OK" : "INVALID"}`,
);
for (const e of res.errors) console.log(`  error: ${e}`);
for (const w of res.warnings) console.log(`  warn:  ${w}`);
console.log(`diff vs ${basename(againstPath)}:`);
for (const d of diff.length ? diff : ["(no change)"]) console.log(`  ${d}`);

const preview = opt("--preview");
if (preview) {
  const md = [
    `# Hotspot preview: ${basename(input)} (v${res.version})`,
    "",
    `- sha256 \`${sha256}\``,
    `- status: **${res.ok ? "valid" : "INVALID"}** (${res.errors.length} errors, ${res.warnings.length} warnings)`,
    `- compared with: \`${againstPath.replace(root + "/", "")}\` (laptop composition only; tablet/mobile unchanged)`,
    "",
    "## Errors",
    ...(res.errors.length ? res.errors.map((e) => `- ${e}`) : ["- none"]),
    "",
    "## Warnings",
    ...(res.warnings.length ? res.warnings.map((e) => `- ${e}`) : ["- none"]),
    "",
    "## Diff (order is later-wins; rects are [x1,y1,x2,y2] exclusive)",
    "",
    ...(diff.length ? diff.map((d) => `- \`${d}\``) : ["- no change"]),
    "",
    "## Imported rects",
    "",
    "| id | route | rects (first = focusable) | from |",
    "| --- | --- | --- | --- |",
    ...res.hotspots.map(
      (h) =>
        `| ${h.id} | ${h.route} | ${h.rects.map((r) => `[${r}]`).join(" ")} | ${h.from.join(", ")} |`,
    ),
    "",
  ].join("\n");
  writeFileSync(resolve(preview), md);
  console.log(`preview -> ${resolve(preview)}`);
}

if (args.includes("--write")) {
  if (!res.ok) {
    console.error("not written: fix the errors first");
    process.exit(1);
  }
  const src = `/**
 * GENERATED by scripts/hotspots/import-hotspots.mjs. Do not edit by hand:
 * re-run the importer on the next HOTSPOT_BOXES_*.json instead (docs/hotspots.md).
 */
import type { Rect } from "../hit-areas";

export const LAPTOP_BOXES_SOURCE = ${JSON.stringify({
    file: basename(input),
    task: res.task,
    version: res.version,
    sha256,
  })} as const;

/** Laptop stacking order, later wins (z-index, not DOM order). */
export const LAPTOP_HIT_ORDER = ${JSON.stringify(res.order)} as const;

/** Laptop rects per hotspot id; first = focusable, rest pointer-only. */
export const LAPTOP_RECTS: Record<string, Rect[]> = ${JSON.stringify(
    Object.fromEntries(res.hotspots.map((h) => [h.id, h.rects])),
  )};

/** Box-file provenance of each rect above. */
export const LAPTOP_RECT_FROM: Record<string, string[]> = ${JSON.stringify(
    Object.fromEntries(res.hotspots.map((h) => [h.id, h.from])),
  )};
`;
  const prettier = await import("prettier");
  const conf = (await prettier.resolveConfig(GENERATED)) ?? {};
  writeFileSync(
    GENERATED,
    await prettier.format(src, { ...conf, filepath: GENERATED }),
  );
  console.log(`wrote ${GENERATED.replace(root + "/", "")}`);
}
process.exit(res.ok ? 0 : 1);
